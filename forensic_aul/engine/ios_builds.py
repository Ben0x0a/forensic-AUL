"""Best-effort iOS build-code → marketing-version lookup.

Defines : ios_version_for_build (the lookup) and load_build_table (the data).
Used by : forensic_aul/ops/extraction/extract.py (iOS-version fallback for
          logarchive-dir sources); scripts/update_ios_builds.py (reads the
          table it regenerates).
Uses    : ios_builds.json beside this module (package data), read once via
          importlib.resources.

When an authoritative ``SystemVersion.plist`` is present (full-file-system and
sysdiagnose sources) the exact ``ProductVersion`` is used and this table is not
consulted. A bare ``.logarchive`` directory, however, carries only the **build
code** (e.g. ``21F90``) in its tracev3 header, so this maps a build back to a
human iOS version as a convenience.

IMPORTANT (forensic accuracy):
  - The table is best-effort: an unknown build returns ``None`` and the caller
    keeps showing the raw build code rather than guessing.
  - The authoritative source remains ``SystemVersion.plist``.

WHY a data file regenerated by a script instead of a dict in code: new builds
ship every few weeks, and a hand-kept table in code was always behind (build
22B91 resolved to nothing). The script rewrites the file from a public firmware
list; the diff shows exactly which builds were added.
"""

from __future__ import annotations

import json
from functools import cache
from importlib.resources import files

# The data file's name, next to this module. Consumed by: load_build_table and
# scripts/update_ios_builds.py.
TABLE_FILENAME = "ios_builds.json"


@cache
def load_build_table() -> dict[str, str]:
    """The whole table: upper-case build code → iOS marketing version."""
    raw = files("forensic_aul.engine").joinpath(TABLE_FILENAME).read_text(encoding="utf-8")
    return {build.upper(): version for build, version in json.loads(raw)["builds"].items()}


def ios_version_for_build(build: str | None) -> str | None:
    """Return the iOS marketing version for *build*, or None if unknown.

    Matching is exact and case-insensitive on the trimmed build code; a miss
    returns None so the caller can fall back to displaying the raw build.
    """
    if not build:
        return None
    return load_build_table().get(build.strip().upper())
